/**
 * seed-training.mjs — snapshot the CURRENT training_samples from a Supabase database into
 * supabase/seed.sql, so a fresh `supabase db reset` comes up with a real, hand-drawn training set
 * (the recognizer doesn't start from nothing).
 *
 *   SUPABASE_SECRET=<secret key> node tools/seed-training.mjs     (or: npm run seed:training)
 *   env: SUPABASE_URL (default http://127.0.0.1:54321), SUPABASE_SECRET (required)
 *
 * Each active sample becomes an INSERT keyed by the symbol's engine_id (UUIDs change across resets),
 * preserving its points / role / source / app_version. The block is written between markers and is
 * idempotent (re-running replaces it). LOCAL/DEV: uses the service key, so run it against a local DB.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { createClient } from '@supabase/supabase-js'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const SEED = path.join(ROOT, 'supabase', 'seed.sql')
const BEGIN = '-- >>> training seed (generated by tools/seed-training.mjs — snapshot of real samples)'
const END = '-- <<< training seed'

const url = process.env.SUPABASE_URL || 'http://127.0.0.1:54321'
const secret = process.env.SUPABASE_SECRET
if (!secret) { console.error('Set SUPABASE_SECRET (the local "Secret" key from `npx supabase status`).'); process.exit(1) }

const db = createClient(url, secret, { auth: { autoRefreshToken: false, persistSession: false } })

const { data, error } = await db
  .from('training_samples')
  .select('points, role, source, app_version, symbols ( engine_id )')
  .is('deleted_at', null)
if (error) { console.error('query failed:', error.message); process.exit(1) }

const rows = []
for (const r of data || []) {
  const engineId = r.symbols?.engine_id
  if (!engineId || !Array.isArray(r.points) || r.points.length < 2) continue
  const json = JSON.stringify(r.points).replace(/'/g, "''")
  const role = (r.role || 'sign').replace(/'/g, "''")
  const source = (r.source || 'drawn').replace(/'/g, "''")
  const app = (r.app_version || 'studio').replace(/'/g, "''")
  rows.push(
    `insert into public.training_samples (symbol_id, points, role, source, app_version)\n` +
    `select id, '${json}'::jsonb, '${role}', '${source}', '${app}' from public.symbols where engine_id = '${engineId.replace(/'/g, "''")}';`,
  )
}

// Ship the seed pre-verified so a fresh `supabase db reset` comes up with a trained DB-overlay base
// (the verified=true path). verified_by stays null (system seed, not an admin action).
const VERIFY_ALL = [
  '-- Seed baseline pre-verified: a fresh clone gets a trained DB-overlay base out of the box.',
  'update public.training_samples set verified = true, verified_at = now()',
  ' where verified = false and deleted_at is null;',
].join('\n')

const block = [BEGIN, `-- ${rows.length} real training samples snapshotted from ${url}.`, ...rows, VERIFY_ALL, END, ''].join('\n')

let sql = fs.readFileSync(SEED, 'utf8')
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
const re = new RegExp(`\\n?${esc(BEGIN)}[\\s\\S]*?${esc(END)}\\n?`)
sql = sql.replace(re, '\n')
if (!sql.endsWith('\n')) sql += '\n'
sql += '\n' + block
fs.writeFileSync(SEED, sql)
console.log(`seed-training: wrote ${rows.length} training_samples inserts into supabase/seed.sql`)
